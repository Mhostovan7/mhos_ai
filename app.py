@app.post("/chat")
async def chat(request: ChatRequest):

    try:

        # -------------------------------------------------
        # ساخت Prompt
        # -------------------------------------------------

        prompt = build_prompt(request)

        # -------------------------------------------------
        # ارسال درخواست به DeepSeek
        # -------------------------------------------------

        response = model.generate_content(
            prompt
        )

        # -------------------------------------------------
        # گرفتن متن پاسخ
        # -------------------------------------------------

        raw_answer = response.text

        # -------------------------------------------------
        # تبدیل پاسخ AI به JSON
        # -------------------------------------------------

        result = parse_ai_response(
            raw_answer
        )

        # -------------------------------------------------
        # برگرداندن نتیجه به Flutter
        # -------------------------------------------------

        return {
            "success": True,
            "result": result
        }

    except Exception as e:

        # -------------------------------------------------
        # نمایش خطای کامل در ترمینال
        # -------------------------------------------------

        traceback.print_exc()

        return {
            "success": False,
            "result": {},
            "error": str(e)
        }


