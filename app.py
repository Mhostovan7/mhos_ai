# تبدیل پاسخ AI به JSON
# =========================================================

def parse_ai_response(text: str):

    text = text.strip()

    # -----------------------------------------------------
    # حذف Markdown احتمالی
    # -----------------------------------------------------

    if text.startswith("```"):

        lines = text.splitlines()

        # حذف ```json
        if len(lines) > 0:
            lines = lines[1:]

        # حذف ``` انتهایی
        if len(lines) > 0:
            if lines[-1].strip() == "```":
                lines = lines[:-1]

        text = "\n".join(lines).strip()

    # -----------------------------------------------------
    # تلاش برای JSON
    # -----------------------------------------------------

    try:

        result = json.loads(text)

        if not isinstance(result, dict):
            raise ValueError(
                "AI response is not an object"
            )

        return result

    except Exception:

        # اگر مدل JSON معتبر نداد،
        # پاسخ را به عنوان گفتگوی معمولی برمی‌گردانیم.

        return {
            "answer_ai_to_user": text,
            "type": "conversation",
            "reminder": None
        }


